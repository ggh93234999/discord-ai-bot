// 結算畫面上的名稱（例如「役牌 中」「正花 春」「連2拉2」「紅中」）對到表裡的哪一項
export function guideKey(rule, name) {
  const n = String(name).replace(/（.*）$/, "");
  if (rule === "jp") { if (n.startsWith("役牌")) return "役牌 白／發／中"; return n; }
  if (/^連\d+拉\d+/.test(n)) return "連 N 拉 N";
  if (["紅中", "青發", "白板"].includes(n)) return "三元牌（紅中／青發／白板）";
  if (n.startsWith("正花")) return "正花";
  if (n === "春夏秋冬" || n === "梅蘭竹菊") return "花槓";
  return n;
}
export function guideItem(rule, name) {
  const k = guideKey(rule, name);
  for (const g of GUIDE[rule].groups) for (const it of g.items) if (it[0] === k) return it;
  return null;
}
// 範例字串 → 牌的編號
export function parseTiles(s) {
  const out = [];
  for (const g of String(s).match(/\d+[mpszf]/g) || []) {
    const k = g.slice(-1);
    for (const d of g.slice(0, -1)) {
      const v = Number(d) - 1;
      out.push(k === "z" ? 27 + v : k === "f" ? 34 + v : { m: 0, p: 9, s: 18 }[k] + v);
    }
  }
  return out;
}
